    // ---------------------------------------------------------------
    //  Public API
    // ---------------------------------------------------------------

    public static int mg(int pieceType, int square) {
        return MG[pieceType][square];
    }

    public static int eg(int pieceType, int square) {
        return EG[pieceType][square];
    }

    /** Rotate square by 180° for white's perspective. */
    public static int mirrorSquare(int square) {
        int rank = square / 9;
        int file = square % 9;
        return (8 - rank) * 9 + (8 - file);
    }

    // ---------------------------------------------------------------
    //  Helpers
    // ---------------------------------------------------------------

    /** Fill a table by rank-major template. */
    private static void fill(int[][] table, int pieceType, int[] values) {
        System.arraycopy(values, 0, table[pieceType], 0, SQUARES);
    }

